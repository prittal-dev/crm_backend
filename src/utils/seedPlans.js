export const seedDefaultPlans = async () => {
  try {
    const validCodes = DEFAULT_PLANS.map(p => p.code);
    // Remove obsolete legacy plans so only exact official plans exist
    await Plan.deleteMany({ code: { $nin: validCodes } });

    for (const planData of DEFAULT_PLANS) {
      await Plan.findOneAndUpdate(
        { code: planData.code },
        { $set: planData },
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    }
    console.log(`📦 [Seed]: Cleaned legacy plans. All ${DEFAULT_PLANS.length} Prittal Pricing Plans synchronized successfully.`);
  } catch (err) {
    console.error('Error seeding default plans:', err.message);
  }
};
