export const getFestivalDateByName = (taskName, fallbackDate = '') => {
    if (!taskName || typeof taskName !== 'string') return fallbackDate;
    const clean = taskName.toLowerCase().trim();

    let targetYear = String(new Date().getFullYear());
    if (fallbackDate && typeof fallbackDate === 'string') {
        const parts = fallbackDate.split('T')[0].split('-');
        if (parts.length >= 1 && parts[0].length === 4) {
            targetYear = parts[0];
        }
    }

    let matchedFest = FESTIVALS_AND_HOLIDAYS.find(f => {
        if (!f.date.startsWith(targetYear)) return false;
        const fname = f.name.toLowerCase();
        if (clean.includes(fname)) return true;
        const mainPart = fname.split('/')[0].split('(')[0].trim();
        return mainPart.length >= 4 && clean.includes(mainPart);
    });

    if (!matchedFest) {
        matchedFest = FESTIVALS_AND_HOLIDAYS.find(f => {
            const fname = f.name.toLowerCase();
            if (clean.includes(fname)) return true;
            const mainPart = fname.split('/')[0].split('(')[0].trim();
            return mainPart.length >= 4 && clean.includes(mainPart);
        });
    }

    if (matchedFest && matchedFest.date) {
        const parts = matchedFest.date.split('-');
        if (parts.length === 3) {
            const festDateObj = new Date(parseInt(parts[0], 10), parseInt(parts[1], 10) - 1, parseInt(parts[2], 10));
            if (festDateObj.getDay() === 0) {
                const satDate = new Date(festDateObj.getFullYear(), festDateObj.getMonth(), festDateObj.getDate() - 1);
                const sy = satDate.getFullYear();
                const sm = String(satDate.getMonth() + 1).padStart(2, '0');
                const sd = String(satDate.getDate()).padStart(2, '0');
                return `${sy}-${sm}-${sd}`;
            }
        }
        return matchedFest.date;
    }

    return fallbackDate;
};

